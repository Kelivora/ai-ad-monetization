import type { AdFormat } from '../../../../knowledge/schema.js';

/** 冷烟测试模板参数：包名来自 pubspec.yaml 的 name，检查项由 formats 决定。 */
export interface SmokeTestOptions {
  packageName: string;
  formats: AdFormat[];
}

/**
 * 生成 integration_test/ads_smoke_test.dart（全英文）。
 * 每项检查独立执行，结束打印一行机器可读结果 AI_AD_SMOKE {json}（失败也先打印再 expect）。
 * 关键约束：全屏广告展示期间 Flutter 不再出帧，tester.pump 会卡死，
 * 因此 rewarded show 之后只能用 Future.delayed 轮询。
 */
export function renderAdsSmokeTest(opts: SmokeTestOptions): string {
  const hasBanner = opts.formats.includes('banner');
  const hasInterstitial = opts.formats.includes('interstitial');
  const hasRewarded = opts.formats.includes('rewarded');

  const bannerTest = hasBanner
    ? `
  testWidgets('banner_loaded', (tester) async {
    await _runCheck('banner_loaded', () async {
      LoadAdError? loadError;
      await tester.pumpWidget(
        MaterialApp(
          home: Scaffold(
            bottomNavigationBar: AnchoredBannerAd(
              onAdFailedToLoad: (LoadAdError error) {
                loadError ??= error;
              },
            ),
          ),
        ),
      );
      final bool found = await _pumpUntil(
        tester,
        () => find.byType(AdWidget).evaluate().isNotEmpty,
      );
      if (found) return _SmokeResult(true, 'AdWidget rendered');
      return _SmokeResult(false, _loadErrorDetail(loadError));
    });
  });
`
    : '';

  const interstitialTest = hasInterstitial
    ? `
  testWidgets('interstitial_loaded', (tester) async {
    await _runCheck('interstitial_loaded', () async {
      final InterstitialAdController controller = InterstitialAdController();
      await controller.load();
      final bool ready = await _pumpUntil(tester, () => controller.isReady);
      final LoadAdError? loadError = controller.lastLoadError;
      controller.dispose();
      if (ready) return _SmokeResult(true, 'interstitial ad ready');
      return _SmokeResult(false, _loadErrorDetail(loadError));
    });
  });
`
    : '';

  const rewardedTests = hasRewarded
    ? `
  testWidgets('rewarded_loaded', (tester) async {
    await _runCheck('rewarded_loaded', () async {
      final RewardedAdController controller = RewardedAdController();
      await controller.load();
      final bool ready = await _pumpUntil(tester, () => controller.isReady.value);
      final LoadAdError? loadError = controller.lastLoadError;
      controller.dispose();
      if (ready) return _SmokeResult(true, 'rewarded ad ready');
      return _SmokeResult(false, _loadErrorDetail(loadError));
    });
  });

  testWidgets('rewarded_reward_callback', (tester) async {
    if (!_showFullscreen) {
      debugPrint(
        'AI_AD_SMOKE \${jsonEncode(<String, Object?>{
          'check': 'rewarded_reward_callback',
          'ok': true,
          'skipped': true,
          'detail': 'set --dart-define=ADS_SMOKE_SHOW_FULLSCREEN=true to enable',
        })}',
      );
      return;
    }
    await _runCheck('rewarded_reward_callback', () async {
      final RewardedAdController controller = RewardedAdController();
      await controller.load();
      final bool ready = await _pumpUntil(tester, () => controller.isReady.value);
      if (!ready) {
        controller.dispose();
        return _SmokeResult(false, 'rewarded ad not ready within 45s');
      }
      bool earned = false;
      String rewardDetail = '';
      await controller.show(
        onReward: (RewardItem reward) {
          earned = true;
          rewardDetail = '\${reward.amount} \${reward.type}';
        },
      );
      // A fullscreen ad is showing: the engine stops producing frames, so
      // tester.pump would hang. Poll with real-time delays only.
      final bool gotReward = await _delayUntil(() => earned);
      controller.dispose();
      return _SmokeResult(
        gotReward,
        gotReward
            ? 'onReward fired (reward: \$rewardDetail)'
            : 'onReward did not fire within 90s',
      );
    });
  });
`
    : '';

  return `// Generated by ai-ad-monetization. Cold smoke test for the generated AdMob
// integration: loads real test ads with Google's test ad unit IDs (network
// required) and prints one machine-readable AI_AD_SMOKE result line per
// check. Each check is independent; a failure does not stop the others.
//
// Run on a connected emulator or device:
//   flutter test integration_test/ads_smoke_test.dart -d <device>
// Optional dart-defines:
//   --dart-define=ADS_SMOKE_TEST_DEVICE_ID=<id>  EEA consent check on a
//     physical device needs its test device id.
//   --dart-define=ADS_SMOKE_SHOW_FULLSCREEN=true  also show the rewarded ad
//     and wait for the onReward callback (dismiss the ad manually).

import 'dart:async';
import 'dart:convert';

import 'package:${opts.packageName}/ads/ads.dart';
import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:google_mobile_ads/google_mobile_ads.dart';
import 'package:integration_test/integration_test.dart';

const bool _showFullscreen = bool.fromEnvironment('ADS_SMOKE_SHOW_FULLSCREEN');
const String _testDeviceId = String.fromEnvironment('ADS_SMOKE_TEST_DEVICE_ID');

class _SmokeResult {
  _SmokeResult(this.ok, this.detail);

  final bool ok;
  final String detail;
}

/// Runs one check, prints its machine-readable AI_AD_SMOKE line (even on
/// failure), then asserts, so the result is always parseable from the log.
Future<void> _runCheck(String check, Future<_SmokeResult> Function() body) async {
  final Stopwatch stopwatch = Stopwatch()..start();
  _SmokeResult result;
  try {
    result = await body();
  } catch (e) {
    result = _SmokeResult(false, 'exception: \$e');
  }
  stopwatch.stop();
  debugPrint(
    'AI_AD_SMOKE \${jsonEncode(<String, Object?>{
      'check': check,
      'ok': result.ok,
      'ms': stopwatch.elapsedMilliseconds,
      'detail': result.detail,
    })}',
  );
  expect(result.ok, isTrue, reason: '\$check: \${result.detail}');
}

/// Polls with real frame pumps (safe while no fullscreen ad is showing).
Future<bool> _pumpUntil(
  WidgetTester tester,
  bool Function() condition, {
  int timeoutSeconds = 45,
}) async {
  final DateTime end = DateTime.now().add(Duration(seconds: timeoutSeconds));
  while (DateTime.now().isBefore(end)) {
    await tester.pump(const Duration(milliseconds: 250));
    if (condition()) return true;
    await Future<void>.delayed(const Duration(milliseconds: 250));
  }
  return condition();
}

/// Polls with wall-clock delays only: while a fullscreen ad is showing the
/// engine produces no frames and tester.pump would hang forever.
Future<bool> _delayUntil(
  bool Function() condition, {
  int timeoutSeconds = 90,
}) async {
  final DateTime end = DateTime.now().add(Duration(seconds: timeoutSeconds));
  while (DateTime.now().isBefore(end)) {
    if (condition()) return true;
    await Future<void>.delayed(const Duration(milliseconds: 500));
  }
  return condition();
}

Future<FormError?> _requestConsentInfoUpdate(
  ConsentRequestParameters parameters,
) {
  final Completer<FormError?> completer = Completer<FormError?>();
  ConsentInformation.instance.requestConsentInfoUpdate(
    parameters,
    () => completer.complete(null),
    completer.complete,
  );
  return completer.future;
}

/// Human-readable load error for a failed *_loaded check; the code/domain
/// prefix is parsed by the verify runtime for diagnosis.
String _loadErrorDetail(LoadAdError? error) {
  if (error != null) {
    return 'load error: code=\${error.code} domain=\${error.domain} '
        'message=\${error.message}';
  }
  return 'no load error reported (still loading or timed out)';
}

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('consent_eea', (tester) async {
    await _runCheck('consent_eea', () async {
      ConsentInformation.instance.reset();
      final ConsentRequestParameters parameters = ConsentRequestParameters(
        consentDebugSettings: ConsentDebugSettings(
          debugGeography: DebugGeography.debugGeographyEea,
          testIdentifiers:
              _testDeviceId.isEmpty ? <String>[] : <String>[_testDeviceId],
        ),
      );
      final FormError? error = await _requestConsentInfoUpdate(parameters);
      final ConsentStatus status =
          await ConsentInformation.instance.getConsentStatus();
      final bool formAvailable =
          await ConsentInformation.instance.isConsentFormAvailable();
      // Leave consent state clean for the following checks.
      ConsentInformation.instance.reset();
      if (error != null) {
        return _SmokeResult(
          false,
          'requestConsentInfoUpdate failed: \${error.errorCode} \${error.message} '
          '(on a physical device pass --dart-define=ADS_SMOKE_TEST_DEVICE_ID=<test device id>; '
          'the GDPR message must be published in AdMob Privacy & messaging)',
        );
      }
      if (status != ConsentStatus.required) {
        return _SmokeResult(
          false,
          'consent status \$status, expected ConsentStatus.required',
        );
      }
      if (!formAvailable) {
        return _SmokeResult(
          false,
          'consent form not available (publish the GDPR message in AdMob '
          'Privacy & messaging first)',
        );
      }
      return _SmokeResult(true, 'status=required formAvailable=true');
    });
  });

  testWidgets('sdk_initialized', (tester) async {
    await _runCheck('sdk_initialized', () async {
      final bool initialized = await AdsInitializer.instance.initialize();
      return _SmokeResult(
        initialized,
        initialized
            ? 'AdsInitializer.initialize returned true'
            : 'AdsInitializer.initialize returned false',
      );
    });
  });
${bannerTest}${interstitialTest}${rewardedTests}}
`;
}
