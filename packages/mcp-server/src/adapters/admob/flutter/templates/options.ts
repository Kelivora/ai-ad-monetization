import type { AdFormat } from '../../../../knowledge/schema.js';
import type { TestIdsFile } from '../../../../knowledge/schema.js';

/** 模板参数：测试 ID、版本号等一律来自知识库，不在 TS 里硬编码。 */
export interface TemplateOptions {
  pluginVersion: string; // 如 9.2.0
  versionConstraint: string; // 如 ^9.2.0
  testIds: TestIdsFile;
  childDirected: boolean;
  interstitialMinIntervalSeconds: number;
  formats: AdFormat[];
}

export function fileHeader(opts: TemplateOptions): string {
  return `// Generated by ai-ad-monetization (google_mobile_ads ${opts.versionConstraint}). Safe to edit.`;
}

function unit(testIds: TestIdsFile, format: 'banner' | 'interstitial' | 'rewarded', platform: 'android' | 'ios'): string {
  const entry = testIds.adUnits.find((u) => u.format === format);
  return entry ? entry[platform] : '';
}

export function renderAdUnitIds(opts: TemplateOptions): string {
  const bannerAndroid = unit(opts.testIds, 'banner', 'android');
  const bannerIos = unit(opts.testIds, 'banner', 'ios');
  const interstitialAndroid = unit(opts.testIds, 'interstitial', 'android');
  const interstitialIos = unit(opts.testIds, 'interstitial', 'ios');
  const rewardedAndroid = unit(opts.testIds, 'rewarded', 'android');
  const rewardedIos = unit(opts.testIds, 'rewarded', 'ios');
  return `${fileHeader(opts)}

import 'dart:io';

/// 广告单元 ID。
///
/// 默认是 Google 公开的测试 ID（不会产生真实收益）；发布前用
/// \`--dart-define=ADMOB_ANDROID_BANNER_ID=ca-app-pub-xxx/yyy\` 之类的参数覆盖。
class AdUnitIds {
  AdUnitIds._();

  /// Google 测试 ID 的发布者前缀。
  static const String testPublisherPrefix = '${opts.testIds.prefix}';

  static const String androidBannerId = String.fromEnvironment(
    'ADMOB_ANDROID_BANNER_ID',
    defaultValue: '${bannerAndroid}',
  );

  static const String iosBannerId = String.fromEnvironment(
    'ADMOB_IOS_BANNER_ID',
    defaultValue: '${bannerIos}',
  );

  static const String androidInterstitialId = String.fromEnvironment(
    'ADMOB_ANDROID_INTERSTITIAL_ID',
    defaultValue: '${interstitialAndroid}',
  );

  static const String iosInterstitialId = String.fromEnvironment(
    'ADMOB_IOS_INTERSTITIAL_ID',
    defaultValue: '${interstitialIos}',
  );

  static const String androidRewardedId = String.fromEnvironment(
    'ADMOB_ANDROID_REWARDED_ID',
    defaultValue: '${rewardedAndroid}',
  );

  static const String iosRewardedId = String.fromEnvironment(
    'ADMOB_IOS_REWARDED_ID',
    defaultValue: '${rewardedIos}',
  );

  /// 当前平台的横幅广告单元 ID。
  static String get banner => Platform.isIOS ? iosBannerId : androidBannerId;

  /// 当前平台的插屏广告单元 ID。
  static String get interstitial =>
      Platform.isIOS ? iosInterstitialId : androidInterstitialId;

  /// 当前平台的激励视频广告单元 ID。
  static String get rewarded => Platform.isIOS ? iosRewardedId : androidRewardedId;

  /// 任一当前生效的广告单元 ID 是 Google 测试 ID 时为 true（发布口径下必须为 false）。
  static bool get usingTestIds => <String>{
        banner,
        interstitial,
        rewarded,
      }.any((String id) => id.startsWith(testPublisherPrefix));
}
`;
}

export function renderAdsConsent(opts: TemplateOptions): string {
  return `${fileHeader(opts)}

import 'dart:async';

import 'package:flutter/foundation.dart';
import 'package:google_mobile_ads/google_mobile_ads.dart';

/// UMP 同意流程封装（GDPR / 美国州法规消息）。
///
/// 所有方法都不会抛出异常：UMP 未配置消息、网络失败等情况只记录日志，
/// 以免阻塞应用启动。
class AdsConsent {
  AdsConsent._();

  /// 请求同意信息并按需展示同意表单。
  ///
  /// [debugSettings] 可在调试时强制 EEA 地理位置以验证表单流程：
  /// \`\`\`dart
  /// AdsConsent.gather(
  ///   debugSettings: ConsentDebugSettings(
  ///     debugGeography: DebugGeography.debugGeographyEea,
  ///     testIdentifiers: ['<你的设备测试 ID>'],
  ///   ),
  /// );
  /// \`\`\`
  static Future<void> gather({ConsentDebugSettings? debugSettings}) async {
    final FormError? updateError = await _requestConsentInfoUpdate(
      ConsentRequestParameters(consentDebugSettings: debugSettings),
    );
    if (updateError != null) {
      debugPrint(
        'ai-ad-monetization: requestConsentInfoUpdate failed: '
        '\${updateError.errorCode} \${updateError.message}',
      );
      return;
    }
    final FormError? formError = await _loadAndShowConsentFormIfRequired();
    if (formError != null) {
      debugPrint(
        'ai-ad-monetization: loadAndShowConsentFormIfRequired failed: '
        '\${formError.errorCode} \${formError.message}',
      );
    }
  }

  /// UMP 同意状态是否允许请求广告（每次启动都应重新检查）。
  static Future<bool> canRequestAds() => ConsentInformation.instance.canRequestAds();

  /// 是否需要向用户提供"隐私选项"入口（EEA 等监管市场通常为 true）。
  static Future<bool> isPrivacyOptionsRequired() async =>
      await ConsentInformation.instance.getPrivacyOptionsRequirementStatus() ==
      PrivacyOptionsRequirementStatus.required;

  /// 展示隐私选项表单（放在应用的隐私/设置页面入口里调用）。
  static Future<void> showPrivacyOptionsForm() async {
    final Completer<FormError?> completer = Completer<FormError?>();
    ConsentForm.showPrivacyOptionsForm(completer.complete);
    final FormError? error = await completer.future;
    if (error != null) {
      debugPrint(
        'ai-ad-monetization: showPrivacyOptionsForm failed: '
        '\${error.errorCode} \${error.message}',
      );
    }
  }

  /// 重置同意状态（仅调试用）。
  static void reset() => ConsentInformation.instance.reset();

  static Future<FormError?> _requestConsentInfoUpdate(ConsentRequestParameters params) {
    final Completer<FormError?> completer = Completer<FormError?>();
    ConsentInformation.instance.requestConsentInfoUpdate(
      params,
      () => completer.complete(null),
      completer.complete,
    );
    return completer.future;
  }

  static Future<FormError?> _loadAndShowConsentFormIfRequired() {
    final Completer<FormError?> completer = Completer<FormError?>();
    ConsentForm.loadAndShowConsentFormIfRequired(completer.complete);
    return completer.future;
  }
}
`;
}

export function renderAdsInitializer(opts: TemplateOptions): string {
  const requestConfig = opts.childDirected
    ? `
      // 面向儿童：设置 child-directed 标记（COPPA）。
      await MobileAds.instance.updateRequestConfiguration(
        RequestConfiguration(
          tagForChildDirectedTreatment: TagForChildDirectedTreatment.yes,
        ),
      );
`
    : '';
  return `${fileHeader(opts)}

import 'package:flutter/foundation.dart';
import 'package:google_mobile_ads/google_mobile_ads.dart';

import 'ads_consent.dart';

/// 广告 SDK 初始化器：先走 UMP 同意流程，[AdsConsent.canRequestAds] 为真后
/// 才调用 \`MobileAds.instance.initialize()\`。
///
/// \`initialize()\` 幂等：重复调用返回同一个 Future；任何异常都会被吞掉并
/// 返回 false，绝不让 App 因广告初始化崩溃。
class AdsInitializer {
  AdsInitializer._();

  static final AdsInitializer instance = AdsInitializer._();

  /// 初始化完成（可以请求广告）后变为 true。
  final ValueNotifier<bool> ready = ValueNotifier<bool>(false);

  Future<bool>? _pending;

  Future<bool> initialize() => _pending ??= _initialize();

  Future<bool> _initialize() async {
    try {
      // 同意流程失败不会抛异常（见 AdsConsent）。
      await AdsConsent.gather();
      final bool canRequestAds = await AdsConsent.canRequestAds();
      if (!canRequestAds) {
        debugPrint(
          'ai-ad-monetization: consent not granted yet, skipping MobileAds.initialize',
        );
        return false;
      }
${requestConfig}
      await MobileAds.instance.initialize();
      ready.value = true;
      return true;
    } catch (e) {
      debugPrint('ai-ad-monetization: initialize failed: \$e');
      return false;
    }
  }
}
`;
}
